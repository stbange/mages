int art_pixel(char ch, int owner_colour)
{
    if (ch >= '0' && ch <= '9') return ch - '0';
    if (ch >= 'a' && ch <= 'f') return ch - 'a' + 10;
    if (ch == 'X') return owner_colour;
    if (ch == 'x') return palette_darken((uint8_t)owner_colour, 1);
    return -1;
}
